#!/usr/bin/env python3
"""
WiFiSetup Web Assets Packer
Reads web/portal.html, minifies, gzip-compresses, and generates src/portal_html.h
"""

import os
import sys
import gzip
import re
import argparse

def minify_html(content: str) -> str:
    # Remove HTML comments (except conditional comments if any)
    content = re.sub(r'<!--(?!\[if).*?-->', '', content, flags=re.DOTALL)
    # Strip leading/trailing whitespace from each line and skip empty lines
    lines = [line.strip() for line in content.splitlines() if line.strip()]
    return '\n'.join(lines)

def generate_header(input_path: str, output_path: str):
    if not os.path.isfile(input_path):
        print(f"Error: Input file not found: {input_path}", file=sys.stderr)
        sys.exit(1)

    with open(input_path, 'r', encoding='utf-8') as f:
        raw_html = f.read()

    original_len = len(raw_html.encode('utf-8'))
    minified = minify_html(raw_html)
    minified_len = len(minified.encode('utf-8'))

    # Compress with maximum compression and mtime=0 for reproducible builds
    compressed = gzip.compress(minified.encode('utf-8'), compresslevel=9, mtime=0)
    compressed_len = len(compressed)

    savings = ((original_len - compressed_len) / original_len) * 100.0

    # Format bytes as C array
    hex_bytes = [f"0x{b:02x}" for b in compressed]
    lines = []
    for i in range(0, len(hex_bytes), 16):
        lines.append("    " + ", ".join(hex_bytes[i:i+16]))
    array_body = ",\n".join(lines)

    header_content = f"""#pragma once
#include <Arduino.h>

// Auto-generated by tools/pack_web.py from web/portal.html
// DO NOT EDIT DIRECTLY! Edit web/portal.html and re-run tools/pack_web.py
// Original: {original_len} B | Minified: {minified_len} B | Gzipped: {compressed_len} B ({savings:.1f}% reduction)

const size_t PORTAL_HTML_GZ_LEN = {compressed_len};
const uint8_t PORTAL_HTML_GZ[] PROGMEM = {{
{array_body}
}};
"""

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(header_content)

    print("WiFiSetup Web Packer:")
    print(f"  Input:      {input_path}")
    print(f"  Output:     {output_path}")
    print(f"  Original:   {original_len} bytes")
    print(f"  Minified:   {minified_len} bytes")
    print(f"  Gzipped:    {compressed_len} bytes ({savings:.1f}% smaller)")
    print("Done!")

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    default_input = os.path.normpath(os.path.join(script_dir, "..", "web", "portal.html"))
    default_output = os.path.normpath(os.path.join(script_dir, "..", "src", "portal_html.h"))

    parser = argparse.ArgumentParser(description="Pack HTML into compressed PROGMEM header for WiFiSetup")
    parser.add_argument("-i", "--input", default=default_input, help=f"Source HTML file (default: {default_input})")
    parser.add_argument("-o", "--output", default=default_output, help=f"Destination .h file (default: {default_output})")
    args = parser.parse_args()

    generate_header(args.input, args.output)

if __name__ == "__main__":
    main()

